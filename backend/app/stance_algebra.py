"""Typed composition algebra for the phrase cue guard.

The guard does not read a sentence as one cue. It reads a *sequence of
scope-typed clauses*: each matched cue sits in a clause whose contribution
depends on its polarity, its modality, the scope of any negation over it, and
whether a subject-wide quantifier scopes over it. This module gives that
reading a type and gives the combination of clauses an algebra with laws,
instead of the untyped set union and cardinality test the guard used before.

Two directions, four verdicts
-----------------------------

A clause can only ever do one of two things: commit to a direction, or say
nothing. So the algebra is generated by two atoms — ``SUPPORTS`` and
``CONTRADICTS`` — and a verdict is a *set of directions*:

    ABSTAIN_INFO      = {}            (bottom: the empty join)
    SUPPORTS          = {SUPPORTS}
    CONTRADICTS       = {CONTRADICTS}
    ABSTAIN_CONFLICT  = {SUPPORTS, CONTRADICTS}   (top: both at once)

These four elements are exactly the powerset of the two atoms, which is the free
join-semilattice on two generators (a join-semilattice is a commutative,
idempotent monoid, and the free one on ``n`` generators has ``2**n`` elements).
Composition is join = union; it is not the free *distributive* lattice on two
generators, which has six elements and is not needed here. The carrier and the
table are *generated* from that construction (:func:`_build_generator_sets`,
:func:`lattice_join`) rather than written out as a 4x4 ladder, and the algebra
below is the standard one:

* associative, commutative, idempotent (join-semilattice);
* ``ABSTAIN_INFO`` is the identity — it absorbs nothing and, because join is
  monotone, adding an informational clause can never turn a committed direction
  into a different direction;
* two opposing assertions compose to ``ABSTAIN_CONFLICT``, not to a winner:
  there is no order in which one of them "wins", because join is commutative and
  ``{SUPPORTS} | {CONTRADICTS}`` is the same element either way;
* ``ABSTAIN_CONFLICT`` is absorbing, so a later assertion cannot rescue a
  conflict back into a direction.

Why this matters: the defect class it makes unavailable
-------------------------------------------------------

The previous composition step kept a ``set`` of matched stances and read the
verdict off its cardinality: ``next(iter(matches))`` when there was one element,
``None`` when there were two or more. That is a *selection* over an unordered
set, so (a) it has no identity element and therefore no associativity, (b) adding
a clause that says nothing changes the answer whenever the clause is a distinct
member of the set, and (c) two opposing assertions are indistinguishable from
"one support plus one neutral cue" — both are just "two elements". The reason
code was then recovered from *which rejected-reason sets happened to be
singletons*, so a second independent rejection silently collapsed the diagnosis
to a catch-all. Here the only two operations are join and the total map onto the
guard's return shape, so "adding an informational clause blocked a direction" and
"two assertions tied and something picked a winner" are not expressible.

This module is pure: no I/O, no clock, no randomness, and the dataclasses are
frozen. The same clause sequence always yields the same verdict.

The lexical layer (which phrases carry a cue) is deliberately *not* here; this
module never reads text. :mod:`app.semantic_guard` owns the cue inventory and the
regexes, and routes its per-clause decision and its composition through this
module.
"""

from __future__ import annotations

import itertools
from dataclasses import dataclass
from enum import Enum
from types import MappingProxyType
from typing import Iterable, Mapping


class Verdict(Enum):
    """An element of the four-element lattice; the value is its guard code."""

    SUPPORTS = "SUPPORTS"
    CONTRADICTS = "CONTRADICTS"
    ABSTAIN_INFO = "ABSTAIN_INFO"
    ABSTAIN_CONFLICT = "ABSTAIN_CONFLICT"


#: The two direction atoms the lattice is generated by.
_ATOMS: tuple[Verdict, ...] = (Verdict.SUPPORTS, Verdict.CONTRADICTS)


def _build_generator_sets() -> Mapping[Verdict, frozenset[Verdict]]:
    """Enumerate the carrier as the powerset of the atoms, and name each element.

    The elements of the free join-semilattice on ``_ATOMS`` are exactly its
    subsets: ``{}``, ``{p}``, ``{q}``, ``{p, q}``. Naming them is the only thing
    this function decides; the operation is fixed by the subsets.
    """
    keys = tuple(
        frozenset(combination)
        for size in range(len(_ATOMS) + 1)
        for combination in itertools.combinations(_ATOMS, size)
    )

    labels: dict[Verdict, frozenset[Verdict]] = {}
    for key in keys:
        if not key:
            labels[Verdict.ABSTAIN_INFO] = key
        elif len(key) == len(_ATOMS):
            labels[Verdict.ABSTAIN_CONFLICT] = key
        else:
            # A singleton names the direction it contains. Which of the two atoms
            # it is decides the label, so no iteration order is involved.
            labels[_ATOMS[0] if _ATOMS[0] in key else _ATOMS[1]] = key
    return MappingProxyType(labels)


_GENERATORS = _build_generator_sets()

#: The element whose direction set is a given union — total because the carrier
#: is closed under union by construction.
_ELEMENT: Mapping[frozenset[Verdict], Verdict] = MappingProxyType(
    {directions: verdict for verdict, directions in _GENERATORS.items()}
)

#: Iteration order of the enum, which is the module's own definition order.
_CARRIER_ORDER: tuple[Verdict, ...] = tuple(Verdict)


def _rank(verdict: Verdict) -> int:
    """Number of directions an element carries: a rank function for the order."""
    return len(_GENERATORS[verdict])


def is_direction(verdict: Verdict) -> bool:
    """True for a committed direction, False for either abstention."""
    return verdict in _ATOMS


def is_abstention(verdict: Verdict) -> bool:
    return verdict not in _ATOMS


def leq(left: Verdict, right: Verdict) -> bool:
    """The lattice order: ``left <= right`` iff its directions are included."""
    return _GENERATORS[left] <= _GENERATORS[right]


def lattice_join(left: Verdict, right: Verdict) -> Verdict:
    """Least upper bound, computed from the order rather than from union.

    This is the order-theoretic definition; :func:`compose` is the algebraic one
    (union of direction sets). The two agree on all sixteen pairs, which is what
    the composition table asserts.
    """
    bounds = tuple(
        candidate for candidate in _CARRIER_ORDER
        if leq(left, candidate) and leq(right, candidate)
    )
    least = min(bounds, key=_rank)
    return least


def lattice_meet(left: Verdict, right: Verdict) -> Verdict:
    """Greatest lower bound, the dual of :func:`lattice_join`."""
    bounds = tuple(
        candidate for candidate in _CARRIER_ORDER
        if leq(candidate, left) and leq(candidate, right)
    )
    greatest = max(bounds, key=_rank)
    return greatest


def compose(left: Verdict, right: Verdict) -> Verdict:
    """Join of two verdicts: the union of the directions they carry.

    Union of sets is associative, commutative and idempotent, and the empty set
    is its identity, so the laws hold by construction rather than by table.
    """
    return _ELEMENT[_GENERATORS[left] | _GENERATORS[right]]


#: The composition table, generated from the order (every pair's least upper
#: bound), not written by hand. ``test_stance_algebra`` asserts that
#: :func:`compose` agrees with it on all sixteen pairs.
COMPOSITION_TABLE: Mapping[tuple[Verdict, Verdict], Verdict] = MappingProxyType(
    {
        (left, right): lattice_join(left, right)
        for left in _CARRIER_ORDER
        for right in _CARRIER_ORDER
    }
)


def compose_all(items: Iterable["Clause | Verdict"]) -> Verdict:
    """Fold a clause sequence into one verdict.

    The fold is left-to-right only for bookkeeping: composition is associative and
    commutative, so no reordering of the sequence can change the result.
    """
    result = Verdict.ABSTAIN_INFO
    for item in items:
        result = compose(result, item.verdict() if isinstance(item, Clause) else item)
    return result


class Polarity(Enum):
    """The direction a cue proposes, before any scope is considered."""

    SUPPORTS = "SUPPORTS"
    CONTRADICTS = "CONTRADICTS"
    NONE = "NONE"  # an explicit "this does not address the hypothesis" cue


class Modality(Enum):
    """How the clause states its content."""

    ASSERTED = "asserted"
    HEDGED = "hedged"
    INTERROGATIVE = "interrogative"
    CONDITIONAL = "conditional"
    EVIDENTIAL_FRAME = "evidential_frame"


class NegationScope(Enum):
    """Where a negation sits relative to the cue it scopes over."""

    NONE = "none"
    ADJACENT = "adjacent"  # "was not available"
    FRAME = "frame"  # "it is not true that ...", negated premise clause
    VERB_SEPARATED = "verb_separated"  # "did not confirm the checklist was ..."


class QuantifierScope(Enum):
    """Whether a subject quantifier scopes over the cue."""

    NONE = "none"
    SUBJECT_WIDE = "subject_wide"  # "nobody walked through the handover"


# Reason codes. These are the guard's existing codes, unchanged: the map below
# has to land on the same return shape every caller and every pin already uses.
#: The relation value for an explicit neutral cue: the review outcome is "the
#: quote does not address this", which is ``ABSTAIN_INFO`` with a stated reason.
NEUTRAL = "NEUTRAL"

NO_CUE_MATCH = "NO_CUE_MATCH"
CUE_IN_QUESTION = "CUE_IN_QUESTION"
CONDITIONAL_CUE = "CONDITIONAL_CUE"
NEGATED_CUE = "NEGATED_CUE"
EVIDENCE_ABOUTNESS_FRAME = "EVIDENCE_ABOUTNESS_FRAME"
HEDGED_CUE = "HEDGED_CUE"
CONTRAST_CHANGED_CURRENT_STATE = "CONTRAST_CHANGED_CURRENT_STATE"
ALL_MATCHED_CUES_REJECTED = "ALL_MATCHED_CUES_REJECTED"
AMBIGUOUS_CUE_RELATIONS = "AMBIGUOUS_CUE_RELATIONS"


@dataclass(frozen=True)
class Clause:
    """One matched cue, typed by the scope it sits in.

    Cue presence is structural: a clause exists only because a cue matched, and
    a sentence with no matched cue is the empty sequence, whose fold is
    ``ABSTAIN_INFO``. A present cue that names no direction is
    ``polarity is Polarity.NONE`` — the explicit "this does not address it" case.

    ``polarity`` is the direction the cue proposes. ``modality``, ``negation``
    and ``quantifier`` record the scopes read around it; ``superseded`` records
    that a later contrast clause explicitly changed the cue's current status.

    A clause never commits to a direction unless it is asserted, unnegated,
    unquantified and not superseded. Everything else is ``ABSTAIN_INFO`` — the
    guard abstains rather than flipping a cue, so no scope can turn a direction
    into its opposite.
    """

    polarity: Polarity
    modality: Modality = Modality.ASSERTED
    negation: NegationScope = NegationScope.NONE
    quantifier: QuantifierScope = QuantifierScope.NONE
    superseded: bool = False

    def withheld_by(self) -> str | None:
        """The reason this clause asserts nothing, or ``None`` if it commits.

        The order is the order the guard reads the scopes in, so the reported
        reason is the first scope that actually applies, not a set membership
        test that depends on how many reasons happened to occur.
        """
        if self.modality is Modality.INTERROGATIVE:
            return CUE_IN_QUESTION
        if self.modality is Modality.CONDITIONAL:
            return CONDITIONAL_CUE
        if self.negation is not NegationScope.NONE:
            return NEGATED_CUE
        if self.quantifier is QuantifierScope.SUBJECT_WIDE:
            return NEGATED_CUE
        if self.modality is Modality.EVIDENTIAL_FRAME:
            return EVIDENCE_ABOUTNESS_FRAME
        if self.modality is Modality.HEDGED:
            return HEDGED_CUE
        if self.superseded:
            return CONTRAST_CHANGED_CURRENT_STATE
        return None

    def verdict(self) -> Verdict:
        """This clause's contribution to the sentence's verdict."""
        if self.withheld_by() is not None:
            return Verdict.ABSTAIN_INFO
        if self.polarity is Polarity.NONE:
            return Verdict.ABSTAIN_INFO
        if self.polarity is Polarity.SUPPORTS:
            return Verdict.SUPPORTS
        return Verdict.CONTRADICTS

    def certifies(self) -> bool:
        """Whether the clause is accepted (as opposed to withheld)."""
        return self.withheld_by() is None


@dataclass(frozen=True)
class GuardReading:
    """The guard's return shape: a relation value or ``None``, plus a reason."""

    relation: str | None
    reason_code: str | None


def combine_reasons(reasons: Iterable[str], *, saw_cue: bool) -> str:
    """The abstention reason for a set of withheld clauses.

    One distinct reason is reported as itself; two or more are reported as the
    catch-all, because the guard does not rank diagnoses. Deterministic: the
    single reason is taken from a frozenset of size one, so nothing depends on
    which clause was read first.
    """
    distinct = frozenset(reasons)
    if not saw_cue:
        return NO_CUE_MATCH
    if len(distinct) == 1:
        return min(distinct)
    return ALL_MATCHED_CUES_REJECTED


def to_guard_reading(
    verdict: Verdict,
    *,
    abstain_reason: str | None = None,
    explicit_neutral_information: bool = False,
) -> GuardReading:
    """Map a lattice element onto the guard's return shape.

    The lattice does not distinguish the two ways to reach ``ABSTAIN_INFO`` — an
    explicit neutral cue and a clause with no cue at all are both the join
    identity. The flag carries that provenance for the caller's review state; it
    is not part of the algebra.
    """
    if verdict is Verdict.SUPPORTS:
        return GuardReading(Polarity.SUPPORTS.value, None)
    if verdict is Verdict.CONTRADICTS:
        return GuardReading(Polarity.CONTRADICTS.value, None)
    if verdict is Verdict.ABSTAIN_CONFLICT:
        return GuardReading(None, AMBIGUOUS_CUE_RELATIONS)
    if explicit_neutral_information:
        return GuardReading(NEUTRAL, None)
    return GuardReading(None, abstain_reason or NO_CUE_MATCH)


